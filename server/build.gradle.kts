// The image is generated by the Micronaut plugin, as in Quelea: `buildLayers` and `dockerfile` write a ready
// Docker context to build/docker/main, and `docker build` runs on that directory (no Gradle inside Docker).
// Quelea uses the `optimized` image, which needs the micronaut.aot plugin; this server keeps the plain image.
// The base image is pinned here; the plugin default is a moving `eclipse-temurin:25-jre` tag.
// The image runs as an unprivileged user (uid 10001), so the chart can enforce runAsNonRoot.
tasks.named<io.micronaut.gradle.docker.MicronautDockerfile>("dockerfile") {
    getBaseImage().set("eclipse-temurin:25.0.5_8-jre-noble")
    instruction("RUN groupadd --system --gid 10001 menura && useradd --system --uid 10001 --gid menura --no-create-home menura")
    instruction("USER 10001:10001")
}

// Layers keep the file modes of the Gradle cache. Make them world-readable so uid 10001 can read every jar.
tasks.named("buildLayers") {
    doLast {
        outputs.files.asFileTree.forEach { it.setReadable(true, false) }
    }
}
